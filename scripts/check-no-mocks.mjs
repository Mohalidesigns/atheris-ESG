#!/usr/bin/env node
// No-mock gate (WP-10, master plan §2.4). Scans production frontend code for mock data.
//
//   node scripts/check-no-mocks.mjs                 # REPORT mode: print findings, exit 0
//   node scripts/check-no-mocks.mjs --enforce       # ENFORCE mode (from end of WP-16): exit 1 on findings
//   node scripts/check-no-mocks.mjs --report <file> # also write a markdown report
//
// Scanned: esg-frontend/src/{pages,features,components}, excluding *.test.*, *.stories.*, __mocks__/, tests/.
// Flagged:
//   import-mock      import from a mock/fixture/faker/dummy path
//   fake-async       setTimeout-resolved promises or Promise.resolve(<literal>) standing in for API calls
//   dataset          top-level array literal containing object rows (hard-coded table/chart data)
//   suspicious-name  top-level literal whose name says demo/mock/fake/dummy/sample
// A top-level literal that is genuine configuration (e.g. menu definitions) can be allowed by putting
// `// no-mock-gate: config` on the line directly above it.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'esg-frontend', 'src');
const SCAN_DIRS = ['pages', 'features', 'components'].map((d) => join(SRC, d));
const args = process.argv.slice(2);
const enforce = args.includes('--enforce');
const reportIdx = args.indexOf('--report');
const reportFile = reportIdx >= 0 ? args[reportIdx + 1] : null;

const excluded = (p) => /\.(test|spec|stories)\.[jt]sx?$/.test(p) || /(^|\/)(__mocks__|tests?)\//.test(p);
const walk = (dir) => {
  let out = [];
  let entries = [];
  try { entries = readdirSync(dir); } catch { return out; }
  for (const e of entries) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out = out.concat(walk(p));
    else if (/\.[jt]sx?$/.test(p) && !excluded(relative(SRC, p))) out.push(p);
  }
  return out;
};

const findings = [];
const add = (file, line, rule, detail) => findings.push({ file: relative(ROOT, file), line, rule, detail });

for (const file of SCAN_DIRS.flatMap(walk)) {
  const lines = readFileSync(file, 'utf8').split('\n');
  lines.forEach((text, i) => {
    const allowed = i > 0 && /no-mock-gate:\s*config/.test(lines[i - 1]);
    const imp = text.match(/^\s*import .* from ['"]([^'"]+)['"]/);
    if (imp && /(mock|fixture|faker|dummy)/i.test(imp[1])) add(file, i + 1, 'import-mock', imp[1]);
    if (/setTimeout\s*\(\s*\(?\s*\)?\s*=>\s*resolve/.test(text) || /Promise\.resolve\(\s*[[{'"0-9]/.test(text)) {
      add(file, i + 1, 'fake-async', text.trim().slice(0, 80));
    }
    const decl = text.match(/^(?:export\s+)?const\s+(\w+)\s*=\s*([[{])/);
    if (!decl || allowed) return;
    const [, name, open] = decl;
    if (/(demo|mock|fake|dummy|sample)/i.test(name)) add(file, i + 1, 'suspicious-name', name);
    if (open === '[') {
      let rows = 0;
      for (let j = i + 1; j < lines.length && !/^\];?\s*$/.test(lines[j]); j++) if (/^\s+\{/.test(lines[j])) rows++;
      if (/^\s*const\s+\w+\s*=\s*\[\s*\{/.test(text)) rows++;
      if (rows > 0) add(file, i + 1, 'dataset', `${name} (${rows} rows)`);
    }
  });
}

const byFile = {};
for (const f of findings) (byFile[f.file] ||= []).push(f);
const rows = Object.entries(byFile).sort((a, b) => b[1].length - a[1].length);
const totalRows = findings.filter((f) => f.rule === 'dataset')
  .reduce((n, f) => n + Number(f.detail.match(/\((\d+) rows\)/)[1]), 0);

const summary = `${findings.length} findings in ${rows.length} files (${totalRows} hard-coded dataset rows)`;
console.log(`[no-mock-gate] mode=${enforce ? 'ENFORCE' : 'REPORT'}: ${summary}`);
for (const [file, fs] of rows) for (const f of fs) console.log(`  ${file}:${f.line}  ${f.rule}  ${f.detail}`);

if (reportFile) {
  const md = [
    '# No-mock gate report',
    '',
    `Generated by \`scripts/check-no-mocks.mjs\` in **${enforce ? 'ENFORCE' : 'REPORT'}** mode. ` +
      'The gate switches to ENFORCE at the end of WP-16. Regenerate with `npm run check:no-mocks -- --report ../docs/esg-completion/NO_MOCK_REPORT.md` from `esg-frontend/`.',
    '',
    `**${summary}.**`,
    '',
    '| File | Findings | Details |',
    '|---|---|---|',
    ...rows.map(([file, fs]) => `| \`${file}\` | ${fs.length} | ${fs.map((f) => `L${f.line} ${f.rule}: ${f.detail}`).join('<br>')} |`),
    '',
  ].join('\n');
  writeFileSync(join(process.cwd(), reportFile), md);
}

process.exit(enforce && findings.length ? 1 : 0);
